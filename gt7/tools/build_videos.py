#!/usr/bin/env python3
"""Turn the YouTube search harvest (videos.json from the scraper) into
data/videos.js: deduped per track, classified by title (not by which search
found it), live streams and dead guides dropped.

  python3 -I gt7/tools/build_videos.py <videos.json> [raw.json]
"""
import json, os, re, sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'videos.js')
GT = re.compile(r'gt7|gran turismo|gt sport|\bgt\b', re.I)
RULES = [  # first match wins
    ('history', re.compile(r'history|evolution|story|documentary|untold|revival', re.I)),
    ('hotlap', re.compile(r'world record|\bwr\b|hot ?lap|fastest|\d[:\'.]\d\d[.:"]\d{2,3}|lap time challenge|time trial', re.I)),
    ('setup', re.compile(r'tune|setup|set-up|best car|build|\btop \d|which is the best|cars you', re.I)),
    ('guide', re.compile(r'guide|how to|tips|braking|corner|explained|explanation|tutorial|learn|circuit experience', re.I)),
    ('race', re.compile(r'race|onboard|broadcast|endurance|mission|cup|series', re.I)),
]

def kind(v):
    t = v['title']
    if not GT.search(t):
        return 'history' if RULES[0][1].search(t) else 'real'
    for k, rx in RULES:
        if rx.search(t): return k
    return 'race'

def secs(d):
    p = [int(x) for x in d.split(':')]
    s = 0
    for x in p: s = s * 60 + x
    return s

def main():
    src = json.load(open(sys.argv[1]))
    raw = None
    if len(sys.argv) > 2:
        raw = json.load(open(sys.argv[2]))['searches']
        for sr in raw:
            if isinstance(sr['candidates'], str):
                import ast; sr['candidates'] = ast.literal_eval(sr['candidates'])
    out = {}
    for tid, vids in src.items():
        seen, keep = set(), []
        for v in vids:
            if v['id'] in seen: continue
            seen.add(v['id'])
            if secs(v['dur']) >= 3600 or re.search(r'not working|live stream|🔴', v['title'], re.I): continue
            keep.append({'id': v['id'], 'title': v['title'], 'channel': v['channel'], 'dur': v['dur'],
                         'views': v['views'].replace(' views', ''), 'age': v.get('age', ''), 'kind': kind(v)})
        # top up thin kinds from every valid candidate any of this track's searches saw
        if raw:
            pool = {}
            for sr in raw:
                if sr['track'] != tid: continue
                for c in sr['candidates']:
                    if c['reasons'] or c['videoId'] in seen or c['durSec'] >= 3600: continue
                    e = {'id': c['videoId'], 'title': c['title'], 'channel': c['channel'], 'dur': c['dur'],
                         'views': c['views'].replace(' views', ''), 'age': c.get('age', ''), 'n': c['viewsNum']}
                    e['kind'] = kind(e)
                    if re.search(r'not working|live stream|🔴', e['title'], re.I): continue
                    if e['kind'] not in ('real', 'history') and c.get('tier', 9) != 0: continue
                    pool[e['id']] = e
            for k in ['guide', 'hotlap', 'setup', 'race']:
                have = sum(1 for x in keep if x['kind'] == k)
                for e in sorted((e for e in pool.values() if e['kind'] == k), key=lambda e: -e['n'])[:max(0, 2 - have)]:
                    seen.add(e['id']); e.pop('n'); keep.append(e)
        order = ['guide', 'hotlap', 'setup', 'race', 'real', 'history']
        keep.sort(key=lambda x: order.index(x['kind']))
        out[tid] = keep
    with open(OUT, 'w') as f:
        f.write('// Generated by tools/build_videos.py from real YouTube search results (every id\n')
        f.write('// was in a fetched results page). kind is classified from the title.\n')
        f.write('export const VIDEO_KINDS = [["guide","Track guides"],["hotlap","Hot laps & records"],["setup","Best cars & tunes"],["race","Races & onboards"],["real","Real-world onboards"],["history","History"]];\n')
        f.write('export const VIDEOS = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
    n = sum(len(v) for v in out.values())
    print('tracks', len(out), 'videos', n)
    for tid, v in out.items():
        print(f'  {tid:14s} {len(v):2d} ' + ' '.join(f"{k}:{sum(1 for x in v if x['kind']==k)}" for k in ['guide','hotlap','setup','race','real','history']))

main()
