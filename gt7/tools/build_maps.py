#!/usr/bin/env python3
"""geo.json (lat/lon) -> data/maps.js: north-up integer XY in a 1000-unit box,
1000 points per lap at equal arc length (index/1000 = lap fraction)."""
import json, math, os
H = os.path.dirname(os.path.abspath(__file__))
geo = json.load(open(os.path.join(H, "geo.json")))
out = {}
for cid, g in geo.items():
    P = g["pts"]; lat0 = sum(p[0] for p in P) / len(P); c = math.cos(math.radians(lat0))
    xs = [p[1] * c * 111320 for p in P]; ys = [-p[0] * 110540 for p in P]
    mx, my = min(xs), min(ys); span = max(max(xs) - mx, max(ys) - my)
    k = 1000 / span
    pts = [[round((x - mx) * k), round((y - my) * k)] for x, y in zip(xs, ys)]
    out[cid] = {"km": g["km"], "w": max(p[0] for p in pts), "h": max(p[1] for p in pts),
                "mPerUnit": round(span / 1000, 3), "pts": pts}
js = ("// Generated by tools/build_maps.py from OpenStreetMap (ODbL) via tools/osm_tracks.py.\n"
      "// Real circuit geometry: north up, 1000 points per lap at equal arc length,\n"
      "// so pts[i] sits at lap fraction i/1000 from the start/finish line.\n"
      "export const MAPS = " + json.dumps(out, separators=(",", ":")) + ";\n")
open(os.path.join(H, "..", "data", "maps.js"), "w").write(js)
print(len(js) // 1024, "KB", sorted(out))
